def q(s: str) -> str:
    return "'" + s.replace("\\", "\\\\").replace("'", "\\'") + "'"


def arr_str(items: list[str], pad: str = "      ") -> str:
    return ",\n".join(f"{pad}{q(i)}" for i in items)


def arr_obj(items: list[dict], keys: list[str], pad: str = "      ") -> str:
    blocks = []
    for it in items:
        inner = ",\n".join(f"{pad}  {k}: {q(it[k])}" for k in keys)
        blocks.append(f"{pad}{{\n{inner},\n{pad}}}")
    return ",\n".join(blocks)


def emit_service(sid: str, d: dict) -> str:
    body = ",\n".join(f"      {q(p)}" for p in d["body"])
    process = arr_obj(d["process"], ["title", "body"], "      ")
    benefits = arr_obj(d["benefits"], ["title", "body"], "      ")
    faq = arr_obj(d["faq"], ["q", "a"], "      ")
    return f"""  {q(sid)}: {{
    title: {q(d['title'])},
    metaTitle: {q(d['metaTitle'])},
    metaDescription: {q(d['metaDescription'])},
    lead: {q(d['lead'])},
    body: [
{body},
    ],
    highlights: [
{arr_str(d['highlights'])},
    ],
    audienceTitle: {q(d['audienceTitle'])},
    audience: {q(d['audience'])},
    processTitle: {q(d['processTitle'])},
    process: [
{process},
    ],
    deliverablesTitle: {q(d['deliverablesTitle'])},
    deliverables: [
{arr_str(d['deliverables'])},
    ],
    benefitsTitle: {q(d['benefitsTitle'])},
    benefits: [
{benefits},
    ],
    faqTitle: {q(d['faqTitle'])},
    faq: [
{faq},
    ],
    trustTitle: {q(d['trustTitle'])},
    trust: [
{arr_str(d['trust'])},
    ],
    closingTitle: {q(d['closingTitle'])},
    closingBody: {q(d['closingBody'])},
    imgAlt: {q(d['imgAlt'])},
  }}"""


def emit_file(locale: str, data: dict[str, dict]) -> str:
    order = [
        "web-hosting",
        "mobile-app",
        "web-development",
        "e-commerce",
        "digital-marketing",
        "offline-marketing",
    ]
    services = ",\n".join(emit_service(sid, data[sid]) for sid in order)
    var = {"de": "servicePagesDe", "en": "servicePagesEn", "ar": "servicePagesAr"}[locale]
    return f"""import type {{ ServiceId, ServicePageCopy }} from './types'

export const {var}: Record<ServiceId, ServicePageCopy> = {{
{services},
}}
"""


